_is_syncing_actions = False


def _make_default_flag_id(obj):
    safe_name = re.sub(r"\W+", "_", obj.name).strip("_")
    if not safe_name:
        safe_name = "Object"
    return f"flag_{safe_name}"


def _set_default(obj, key, value):
    if key not in obj:
        obj[key] = value


def _update_property_ui(obj, key, description):
    try:
        obj.id_properties_ui(key).update(description=description)
    except Exception:
        pass


def _to_string(value, default=""):
    if value is None:
        return default
    return str(value)


def _normalize_action(action):
    if not isinstance(action, dict):
        return None
    return {
        "targetObjectId": _to_string(action.get("targetObjectId", action.get("target_object_id", ""))),
        "targetObjectName": _to_string(action.get("targetObjectName", action.get("target_object_name", ""))),
        "actionType": _to_string(action.get("actionType", action.get("action_type", "PlayEffect")), "PlayEffect"),
        "actionDescription": _to_string(
            action.get("actionDescription", action.get("action_description", ""))),
        "postEffectType": _to_string(
            action.get("postEffectType", action.get("post_effect_type", "Flash")), "Flash"),
    }


def _parse_event_object_actions(value):
    if value is None:
        return []

    if isinstance(value, str):
        text = value.strip()
        if not text:
            return []
        if text.startswith("[") or text.startswith("{"):
            try:
                loaded = json.loads(text)
                if isinstance(loaded, dict):
                    loaded = [loaded]
                if isinstance(loaded, list):
                    return [
                        action for action in (_normalize_action(item) for item in loaded)
                        if action is not None
                    ]
            except json.JSONDecodeError as error:
                print(f"[LevelEditor] event_object_actions UI JSON parse failed: {error}")

        actions = []
        for item in text.split(";"):
            parts = [part.strip() for part in item.split("|")]
            if not parts or not parts[0]:
                continue
            actions.append({
                "targetObjectId": "",
                "targetObjectName": parts[0],
                "actionType": parts[1] if len(parts) > 1 and parts[1] else "PlayEffect",
                "actionDescription": parts[2] if len(parts) > 2 else "",
                "postEffectType": parts[3] if len(parts) > 3 and parts[3] else "Flash",
            })
        return actions

    if isinstance(value, list):
        return [
            action for action in (_normalize_action(item) for item in value)
            if action is not None
        ]

    return []


def _action_collection_available(obj):
    return obj is not None and hasattr(obj, "level_event_object_actions")


def _sync_custom_property_from_collection(obj):
    if _is_syncing_actions or not _action_collection_available(obj):
        return

    actions = []
    for item in obj.level_event_object_actions:
        actions.append({
            "targetObjectId": item.target_object_id.strip(),
            "targetObjectName": item.target_object_name.strip(),
            "actionType": item.action_type.strip() or "Custom",
            "actionDescription": item.action_description.strip(),
            "postEffectType": item.post_effect_type.strip() or "Flash",
        })
    obj["event_object_actions"] = json.dumps(actions, ensure_ascii=False) if actions else ""
    _update_property_ui(
        obj,
        "event_object_actions",
        "JSON ObjectAction list generated by Event Flag Editor UI")


def _sync_collection_from_custom_property(obj):
    global _is_syncing_actions
    if not _action_collection_available(obj):
        return

    actions = _parse_event_object_actions(obj.get("event_object_actions", ""))
    _is_syncing_actions = True
    try:
        obj.level_event_object_actions.clear()
        for action in actions:
            item = obj.level_event_object_actions.add()
            item.target_object_id = action.get("targetObjectId", "")
            item.target_object_name = action.get("targetObjectName", "")
            item.action_type = action.get("actionType", "PlayEffect") or "PlayEffect"
            item.action_description = action.get("actionDescription", "")
            item.post_effect_type = action.get("postEffectType", "Flash") or "Flash"

        if obj.level_event_object_action_index >= len(obj.level_event_object_actions):
            obj.level_event_object_action_index = max(0, len(obj.level_event_object_actions) - 1)
    finally:
        _is_syncing_actions = False


def _ensure_action_collection_initialized(obj):
    if not _action_collection_available(obj):
        return
    raw_actions = obj.get("event_object_actions", "")
    if len(obj.level_event_object_actions) == 0 and isinstance(raw_actions, str) and raw_actions.strip():
        _sync_collection_from_custom_property(obj)


def _on_event_object_action_changed(self, context):
    obj = self.id_data
    if obj is not None:
        _sync_custom_property_from_collection(obj)


