class MYADDON_OT_add_event_object_action(bpy.types.Operator):
    bl_idname = "myaddon.myaddon_ot_add_event_object_action"
    bl_label = "アクション追加 (Add Object Action)"
    bl_description = "選択中EventFlagへObjectActionを追加します"
    bl_options = {'REGISTER', 'UNDO'}

    def execute(self, context):
        obj = context.object
        if obj is None:
            self.report({'WARNING'}, "No active object selected")
            return {'CANCELLED'}

        ensure_event_flag_properties(obj)
        if not _action_collection_available(obj):
            self.report({'ERROR'}, "ObjectAction collection is not registered")
            return {'CANCELLED'}

        _ensure_action_collection_initialized(obj)
        item = obj.level_event_object_actions.add()
        item.target_object_name = ""
        item.target_object_id = ""
        item.action_type = "PlayEffect"
        item.action_description = ""
        item.post_effect_type = "Flash"
        obj.level_event_object_action_index = len(obj.level_event_object_actions) - 1
        _sync_custom_property_from_collection(obj)
        return {'FINISHED'}


class MYADDON_OT_remove_event_object_action(bpy.types.Operator):
    bl_idname = "myaddon.myaddon_ot_remove_event_object_action"
    bl_label = "アクション削除 (Remove Object Action)"
    bl_description = "選択中EventFlagからObjectActionを削除します"
    bl_options = {'REGISTER', 'UNDO'}

    index: bpy.props.IntProperty(default=-1)

    def execute(self, context):
        obj = context.object
        if obj is None or not _action_collection_available(obj):
            self.report({'WARNING'}, "No EventFlag ObjectAction collection")
            return {'CANCELLED'}

        _ensure_action_collection_initialized(obj)
        index = self.index if self.index >= 0 else obj.level_event_object_action_index
        if index < 0 or index >= len(obj.level_event_object_actions):
            self.report({'WARNING'}, "ObjectAction index is out of range")
            return {'CANCELLED'}

        obj.level_event_object_actions.remove(index)
        obj.level_event_object_action_index = min(index, max(0, len(obj.level_event_object_actions) - 1))
        _sync_custom_property_from_collection(obj)
        return {'FINISHED'}


